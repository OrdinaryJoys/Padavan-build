def require(value, message):
    if not value: raise ValueError(message)

def sha(raw): return hashlib.sha256(raw).hexdigest()

def exact(left, right, message):
    require(type(left) is type(right) and left == right and
            json.dumps(left, sort_keys=True) == json.dumps(right, sort_keys=True), message)

def exports():
    return {PREFIX+'-kernel.config'} | {
        PREFIX+'-'+c+x for c in COMPONENTS for x in ('.c','','.stdout.json')} | {
        PREFIX+'-'+label+suffix for label in OBJECTS for suffix in ('.o','.cmd')}

def generate(inputs, component):
    require(SOURCE_PATHS and COMPONENTS and CASES and set(EXPECTED)=={n for n,_ in CASES}, 'Reviewed built-in contract incomplete')
    require(set(inputs)==set(SOURCE_PATHS), 'Built-in exact source set differs')
    spec=COMPONENTS[component];data=model.literal_data(inputs[spec['harness_key']])
    require(model.model_data_hash(data)==spec['model_data_sha256'], 'Built-in reviewed literal model differs')
    selectors=tuple(o['selector'] for _,o in CASES if o['component']==component)
    for k,w in (('SOURCE_PATHS',spec['paths']),('FUNCTION_SOURCES',spec['functions']),
                ('SOURCE_ONLY_FUNCTION_SOURCES',spec['source_only_functions']),
                ('BODY_ORDER',tuple(spec['functions'])),('CASE_NAMES',selectors),
                ('EXPECTED_ROWS',{o['selector']:EXPECTED[n] for n,o in CASES if o['component']==component})):
        exact(data.get(k,{} if k=='SOURCE_ONLY_FUNCTION_SOURCES' else None),w,'Built-in model differs: '+k)
    bodies={n:model.function(inputs[spec['source_keys'][k]],n) for n,k in spec['functions'].items()}
    only={n:model.function(inputs[spec['source_keys'][k]],n) for n,k in spec['source_only_functions'].items()}
    fragments=data.get('SOURCE_FRAGMENTS',{})
    require(type(fragments)is dict,'Built-in exact source-fragment mapping required')
    for local,values in fragments.items():
        require(local in spec['source_keys'] and type(values)is tuple and bool(values),
                'Built-in exact source-fragment profile differs')
        text=inputs[spec['source_keys'][local]]
        for value in values:
            require(type(value)is str and bool(value) and
                    (text.count(value)==1 if '\n'in value else sum(line.strip()==value.strip()for line in text.splitlines())==1),
                    'Built-in actual source fragment missing/ambiguous: '+local)
    prefix,suffix=data['PREFIX'],data['SUFFIX']
    require(type(prefix)is type(suffix)is str and suffix.count('CASE_ADMISSION')==1,'Built-in admission marker required')
    if 'FUNCTION_DECLARATIONS' in prefix:
        require(prefix.count('FUNCTION_DECLARATIONS')==1,'Built-in prototype marker differs')
        prefix=prefix.replace('FUNCTION_DECLARATIONS','\n'.join(b.split('{',1)[0].rstrip()+';' for b in bodies.values()))
    marker='CASE_ADMISSION'
    admission='if(!('+'||'.join('!strcmp(name,"'+n+'")' for n in selectors)+'))return 91;'
    if component=='raeth':
        require(data.get('CASE_ADMISSION')=='/* CASE_ADMISSION */', 'RAETH explicit handled-flag marker differs')
        marker=data['CASE_ADMISSION']
        admission='\n'.join('if(!strcmp(name,"'+n+'")) handled=1;'for n in selectors)
    generated=prefix+'\n'.join(bodies.values())+suffix.replace(marker,admission)
    require(0<len(generated.encode())<=MAX_SOURCE and all(generated.count(b)==1 for b in bodies.values()),'Built-in complete-body inclusion differs')
    def manifest(mapping, source, execution):
        return {n:dict(source=spec['paths'][mapping[n]],execution=execution,full_body_sha256=sha(b.encode())) for n,b in source.items()}
    return generated,manifest(spec['functions'],bodies,'whole-function'),manifest(spec['source_only_functions'],only,'source-only-not-run')

def validate_rows(rows):
    require(type(rows)is list and len(rows)==len(CASES),'Built-in exact case count differs')
    for row,(name,options) in zip(rows,CASES):
        require(type(row)is dict and set(row)=={'case','inputs','observed'} and row['case']==name,'Built-in case schema/order differs')
        exact(row['inputs'],options,'Built-in fixed case selector differs')
        exact(row['observed'],EXPECTED[name],'Built-in fixed typed observation differs: '+name)

def command(raw):
    require(type(raw) is bytes and 0 < len(raw) <= MAX_COMMAND and b'\0' not in raw, 'Built-in lifecycle command budget/type')
    return raw.decode()

def source_profile(inputs):
    constants={}
    def macro(text,name,wanted,one=True):
        rows=re.findall(r'^#define[ \t]+'+re.escape(name)+r'[ \t]+([^\n]+)',text,re.M)
        values=[re.sub(r'/\*.*?\*/','',v).strip()for v in rows]
        require((len(values)==1 and values[0]==wanted)if one else wanted in values,'Built-in source constant differs: '+name)
        constants[name]=sha('\n'.join(rows).encode())
    macro(inputs['nor_nor'],'DEFAULT_READY_WAIT_JIFFIES','(40UL * HZ)')
    for enum,value in (('spi_nor_ops','SPI_NOR_OPS_READ=0,SPI_NOR_OPS_WRITE,SPI_NOR_OPS_ERASE,SPI_NOR_OPS_LOCK,SPI_NOR_OPS_UNLOCK,'),('spi_nor_option_flags','SNOR_F_USE_FSR=BIT(0),')):
        rows=re.findall(r'enum '+enum+r'\s*\{([^{}]+)\}',inputs['nor_header'])
        require(len(rows)==1 and re.sub(r'\s+','',rows[0])==value,'Built-in actual NOR enum differs: '+enum)
        constants[enum]=sha(rows[0].encode())
    procdata=model.literal_data(inputs['proc_harness'])
    for name,value in procdata['SOURCE_MACROS'].items():macro(inputs['proc_reg'],name,value,name!='PROCREG_DIR')
    for name,value in procdata['SOURCE_FEATURE_MACROS'].items():macro(inputs['proc_config'],name,value,False)
    require(inputs['raeth_raeth'].count('.suppress_bind_attrs = true,')==1,'Built-in RAETH manual bind/unbind guard missing')
    field=re.findall(r'^[ \t]*bool suppress_bind_attrs;',inputs['raeth_device_header'],re.M)
    require(len(field)==1,'Built-in actual driver attribute flag missing')
    bus=model.function(inputs['raeth_bus'],'bus_add_driver')
    require(bus.count('if (!drv->suppress_bind_attrs) {')==1 and bus.count('error = add_bind_files(drv);')==1,
            'Built-in actual bus bind/unbind gating differs')
    require(len(re.findall(r'^#define[ \t]+MAX_RX_RING_NUM[ \t]+4[ \t]*$', inputs['raeth_header'], re.M)) == 1,
            'Built-in RAETH embedded ring count differs')
    for line in ('CONFIG_RAETH=y', 'CONFIG_MTD_SPI_NOR=y', 'CONFIG_CPU_LITTLE_ENDIAN=y', 'CONFIG_SOC_MT7621=y'):
        require(inputs['kernel_config'].splitlines().count(line) == 1, 'Built-in source board selection differs: ' + line)
    macros = {'SPINOR_OP_RDSR':'0x05','SPINOR_OP_RDFSR':'0x70','SPINOR_OP_WREN':'0x06',
              'SPINOR_OP_WRDI':'0x04','SPINOR_OP_CHIP_ERASE':'0xc7','SR_WIP':'BIT(0)','FSR_READY':'BIT(7)'}
    for name, value in macros.items():
        rows = re.findall(r'^#define[ \t]+' + re.escape(name) + r'[ \t]+([^\n]+)', inputs['nor_header'], re.M)
        require(len(rows) == 1 and re.sub(r'/\*.*?\*/','',rows[0]).strip() == value,
                'Built-in NOR source constant differs: ' + name)
    return {'RAETH_builtin':True, 'MAX_RX_RING_NUM':4, 'MTD_SPI_NOR_builtin':True,
            'CPU_LITTLE_ENDIAN':True, 'NOR_macros':macros,'source_constant_sha256':constants, 'model_layout_is_real_kernel_ABI':False,
            'model_variants':{c:v['model_variant']for c,v in COMPONENTS.items()},
            'manual_bind_unbind_guard':{'driver_flag':True,'kernel_consumer_execution':'source-only-not-run',
                'bus_add_driver_full_body_sha256':sha(bus.encode()),'driver_field_sha256':sha(field[0].encode())}}

def embedded_config(raw):
    start,finish=raw.find(b'IKCFG_ST'),raw.find(b'IKCFG_ED')
    require(raw.count(b'IKCFG_ST')==1 and start>=0 and finish>start+8,'Built-in actual embedded config missing/ambiguous')
    decoder=zlib.decompressobj(31)
    config=decoder.decompress(raw[start+8:finish],MAX_SOURCE+1)
    require(len(config)<=MAX_SOURCE and decoder.eof and not decoder.unused_data,'Built-in embedded kernel config invalid/oversized')
    return config

def kernel_binding(inputs, spi_report, artifacts, kernel_config):
    report_raw = model.read_regular(spi_report, MAX_REPORT)
    report = model.decode_json(report_raw)
    require(type(report.get('schema_version')) is int and report['schema_version'] == 1 and report.get('status') == 'PASS' and
            report.get('profile') == 'k2p-4.4' and report.get('phase') == 'final-kernel-image-bound', 'Built-in lifecycle needs completed SPI image proof')
    binding = report.get('kernel_binding', {})
    require(binding.get('whole_byte_equality') is True, 'Built-in lifecycle SPI whole-kernel/image equality absent')
    raw = model.read_regular(spi_report.parent / 'target-spi-kernel-vmlinux.elf', spi.MAX_ELF)
    linked = spi.inspect_elf(raw, 2)
    exact(binding.get('vmlinux'), linked, 'Built-in lifecycle SPI linked kernel identity differs')
    require(binding.get('exports', {}).get('target-spi-kernel-vmlinux.elf') == sha(raw), 'Built-in lifecycle SPI linked kernel digest differs')
    require(embedded_config(model.read_regular(spi_report.parent/'target-spi-kernel-raw.bin',32*1024*1024))==kernel_config,'Built-in compiled config differs from actual image kernel')
    config = kernel_config.decode()
    for line in ('CONFIG_RAETH=y','CONFIG_MTD_SPI_NOR=y','CONFIG_CPU_LITTLE_ENDIAN=y','CONFIG_SOC_MT7621=y'):
        require(config.splitlines().count(line)==1,'Built-in actual kernel profile differs: '+line)
    objects = {}
    for label, (relative, source_key, names, member) in OBJECTS.items():
        stem = PREFIX + '-' + label
        obj, cmd = artifacts[stem + '.o'], artifacts[stem + '.cmd']
        elf, text = spi.inspect_elf(obj, 1), command(cmd)
        require(model.command_member(text, relative), 'Built-in lifecycle selected object command absent')
        require(all(model.command_member(text,m)for m in member), 'Built-in lifecycle source/aggregate/builtin command membership differs')
        if label not in ('raeth_aggregate','raeth_builtin'): require('-D__KERNEL__' in text and '-Werror' in text, 'Built-in lifecycle kernel command flags absent')
        symbols = {}
        for name in names:
            a, b = elf['function_symbols'].get(name, []), linked['function_symbols'].get(name, [])
            require(len(a) == len(b) == 1 and a[0]['bytes'] > 0 and b[0]['bytes'] > 0, 'Built-in lifecycle actual implementation symbol absent/ambiguous: ' + name)
            symbols[name] = dict(object_symbol=a[0], linked_symbol=b[0])
        objects[label] = dict(source_key=source_key, source_sha256=sha(inputs[source_key].encode()), object_file=stem + '.o', command_file=stem + '.cmd', command_sha256=sha(cmd), ELF=elf, required_symbols=list(names), symbol_bindings=symbols)
    return dict(status='PASS', parent_report_file=spi_report.name, parent_report_sha256=sha(report_raw),
                image_sha256=binding['image']['image_sha256'], vmlinux_sha256=linked['sha256'], kernel_config_sha256=sha(kernel_config),
                objects=objects, compiled_exports_sha256={n: sha(v) for n, v in sorted(artifacts.items())},
                whole_kernel_image_equality=True, source_to_compiled_scope=LINK_SCOPE)

def check(trunk, compiler, output, preflight=False, spi_report=None):
    require(type(preflight) is bool and ((preflight and spi_report is None) or (not preflight and spi_report is not None)), 'Built-in lifecycle requires preflight alone or final SPI parent')
    config = model.read_regular(trunk / '.config', MAX_SOURCE).decode()
    require(re.search(r'^CONFIG_LINUXDIR=linux-4\.4\.x$', config, re.M) and re.search(r'^CONFIG_FIRMWARE_PRODUCT_ID="K2P"$', config, re.M), 'Built-in lifecycle requires configured K2P4.4')
    inputs = {k: model.read_regular(trunk.parent / p, MAX_SOURCE).decode() for k, p in SOURCE_PATHS.items()}
    selection=source_profile(inputs)
    qemu = shutil.which('qemu-mipsel'); require(qemu is not None, 'Built-in qemu-mipsel required')
    output.parent.mkdir(parents=True, exist_ok=True)
    payloads,probes,manifests,source_only_manifests,rows={},{},{},{},[]
    with tempfile.TemporaryDirectory(prefix='k2p-builtin-lifecycle-', dir=output.parent) as temporary:
        for component in COMPONENTS:
            generated,manifest,source_only=generate(inputs,component)
            stem=PREFIX+'-'+component
            source,binary=Path(temporary)/(component+'.c'),Path(temporary)/component
            source.write_text(generated)
            run=subprocess.run([str(compiler),*FLAGS,str(source),'-o',str(binary)],capture_output=True,text=True,timeout=90)
            require(run.returncode==0,'Built-in static MIPS compile failed: '+run.stdout+run.stderr)
            raw=model.read_regular(binary,spi.MAX_ELF);elf=resident.validate_static_helper(raw);stdout=[]
            for name,options in CASES:
                if options['component']!=component:continue
                run=subprocess.run([qemu,str(binary),options['selector']],capture_output=True,text=True,timeout=5)
                require(run.returncode==0 and not run.stderr and 0<len(run.stdout.encode())<=65536,'Built-in inert MIPS case failed: '+name+': '+run.stdout+run.stderr)
                rows.append(dict(case=name,inputs=options,observed=model.decode_json(run.stdout)))
                stdout.append(dict(selector=options['selector'],stdout=run.stdout))
            stdout_raw=(json.dumps(stdout,indent=2)+'\n').encode()
            payloads.update({stem+'.c':generated.encode(),stem:raw,stem+'.stdout.json':stdout_raw})
            probes[component]=dict(source_file=stem+'.c',source_sha256=sha(generated.encode()),binary_file=stem,binary_sha256=sha(raw),ELF=elf,
                compile_flags=list(FLAGS),stdout_file=stem+'.stdout.json',stdout_sha256=sha(stdout_raw))
            manifests[component]=manifest;source_only_manifests[component]=source_only
    validate_rows(rows);reference=None
    if not preflight:
        artifacts = {}
        for label, (relative, _, _, _) in OBJECTS.items():
            path = trunk / 'linux-4.4.x' / relative
            artifacts[PREFIX + '-' + label + '.o'] = model.read_regular(path, spi.MAX_ELF)
            artifacts[PREFIX + '-' + label + '.cmd'] = model.read_regular(path.with_name('.' + path.name + '.cmd'), MAX_COMMAND)
        kernel_config = model.read_regular(trunk / 'linux-4.4.x/.config', MAX_SOURCE)
        reference = kernel_binding(inputs, spi_report, artifacts, kernel_config)
        payloads.update(artifacts); payloads[PREFIX + '-kernel.config'] = kernel_config
    for name, payload in payloads.items(): (output.parent / name).write_bytes(payload)
    for component in COMPONENTS: (output.parent / (PREFIX+'-'+component)).chmod(0o755)
    report = dict(schema_version=1, status='PASS', profile='k2p-4.4', phase='early-source-only' if preflight else 'final-built-in-kernel-reference-bound',
                  execution_role=ROLE, required_cases=[n for n,_ in CASES], checks=rows, source_files=SOURCE_PATHS,
                  source_sha256={k: sha(v.encode()) for k, v in inputs.items()}, whole_function_manifest=manifests, source_only_function_manifest=source_only_manifests, probes=probes,
                  source_profile=selection, compiled_binding=reference, compiler=str(compiler), limits=list(LIMITS))
    output.write_text(json.dumps(report, indent=2) + '\n')
    print('Built-in lifecycle initialization: ' + str(len(rows)) + ' inert actual-source static MIPS cases PASS')
    return report

