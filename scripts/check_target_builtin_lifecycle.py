def embedded_config(raw):
    start,finish=raw.find(b'IKCFG_ST'),raw.find(b'IKCFG_ED')
    require(raw.count(b'IKCFG_ST')==1 and start>=0 and finish>start+8,'Built-in actual embedded config missing/ambiguous')
    decoder=zlib.decompressobj(31)
    config=decoder.decompress(raw[start+8:finish],MAX_SOURCE+1)
    require(len(config)<=MAX_SOURCE and decoder.eof and not decoder.unused_data,'Built-in embedded kernel config invalid/oversized')
    return config

