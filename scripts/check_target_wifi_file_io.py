def function(text,name):
    tokens=r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|/\*[\s\S]*?\*/|//[^\n]*'
    masked=re.sub(tokens,lambda m:' '*len(m.group()),text)
    pattern=r'^(?:static\s+)?(?:inline\s+)?(?:void|VOID|int|INT|INT32|BOOLEAN|NDIS_STATUS|UINT|UINT32)\s+'+re.escape(name)+r'\s*\([^;{}]*\)\s*\{'
    found=list(re.finditer(pattern,masked,re.M));require(len(found)==1,'Missing/ambiguous file-IO function '+name)
    start=found[0].start();opening=text.index('{',start);depth=0
    for token in re.finditer(tokens+r'|[{}]',text[opening:]):
        if token.group()=='{':depth+=1
        elif token.group()=='}':
            depth-=1
            if not depth:return text[start:opening+token.end()]
    raise ValueError('Unterminated file-IO function '+name)

def literal_data(source):
    """Read only constant data/aliases; source generator functions never run."""
    values={}
    def value(node):
        if isinstance(node,ast.Name):
            require(node.id in values,'Unknown file-IO literal alias');return values[node.id]
        if isinstance(node,ast.BinOp)and isinstance(node.op,ast.Add):
            left,right=value(node.left),value(node.right)
            require(type(left)is str and type(right)is str,'File-IO concatenation requires strings');return left+right
        if isinstance(node,ast.Dict):return {value(k):value(v)for k,v in zip(node.keys,node.values)}
        if isinstance(node,(ast.Tuple,ast.List)):
            items=[value(v)for v in node.elts];return tuple(items)if isinstance(node,ast.Tuple)else items
        if isinstance(node,ast.Call)and isinstance(node.func,ast.Name)and node.func.id=='tuple'and len(node.args)==1 and not node.keywords:
            item=value(node.args[0]);require(type(item)in(dict,list,tuple),'File-IO tuple literal input');return tuple(item)
        return ast.literal_eval(node)
    for node in ast.parse(source).body:
        require(isinstance(node,(ast.Import,ast.Assign,ast.FunctionDef))or isinstance(node,ast.Expr)and
                isinstance(node.value,ast.Constant)and type(node.value.value)is str,'Unsupported file-IO generator top-level execution')
        if isinstance(node,ast.Import):require(all(a.name in('hashlib','json','re')for a in node.names),'Unexpected file-IO generator import')
        if isinstance(node,ast.Assign):
            require(len(node.targets)==1 and isinstance(node.targets[0],ast.Name),'Unsupported file-IO data assignment')
            require(node.targets[0].id not in values,'Duplicate file-IO data assignment')
            values[node.targets[0].id]=value(node.value)
    return values

