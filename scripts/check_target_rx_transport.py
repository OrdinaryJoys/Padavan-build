def check(trunk, compiler, output, preflight=False, wifi_report=None):
    validate_contract()
    require(type(preflight) is bool and ((preflight and wifi_report is None) or
            (not preflight and wifi_report is not None)), 'RX requires preflight alone or completed Factory report')
    config = read_regular(trunk / '.config', MAX_SOURCE).decode('utf-8')
    require(re.search(r'^CONFIG_LINUXDIR=linux-4\.4\.x$', config, re.M) and
            re.search(r'^CONFIG_FIRMWARE_PRODUCT_ID="K2P"$', config, re.M), 'RX gate requires configured K2P4.4')
    inputs = {k: read_regular(trunk.parent / p, MAX_SOURCE).decode('utf-8') for k, p in SOURCE_PATHS.items()}
    source_selection(inputs)
    qemu = shutil.which('qemu-mipsel')
    require(qemu is not None, 'qemu-mipsel required')
    rows, probes, manifests, exports = [], {}, {}, {}
    with tempfile.TemporaryDirectory(prefix='k2p-rx-transport-source-', dir='/tmp') as temporary:
        base = Path(temporary)
        for component, spec in COMPONENTS.items():
            probes[component], manifests[component] = {}, {}
            for variant in spec['variants']:
                generated, manifest = generate_component(inputs, component, variant)
                stem = 'target-rx-transport-' + component + '-' + variant
                source, binary = base / (stem + '.c'), base / stem
                source.write_text(generated)
                run = subprocess.run([str(compiler), *FLAGS, str(source), '-o', str(binary)],
                                     capture_output=True, text=True, timeout=90)
                require(run.returncode == 0, 'RX static MIPS compile failed: ' + run.stdout + run.stderr)
                data = read_regular(binary, MAX_ELF)
                elf = resident.validate_static_helper(data)
                stdout_rows = []
                for name, options in CASES:
                    if options['component'] != component or options['variant'] != variant:
                        continue
                    run = subprocess.run([qemu, str(binary), options['selector']], capture_output=True,
                                         text=True, timeout=MAX_CASE_SECONDS)
                    require(run.returncode == 0 and not run.stderr and len(run.stdout.encode()) <= MAX_STDOUT,
                            'RX inert MIPS case failed ' + name + ': ' + run.stdout + run.stderr)
                    observed = decode_json(run.stdout)
                    rows.append({'case': name, 'inputs': options, 'observed': observed})
                    stdout_rows.append({'selector': options['selector'], 'stdout': run.stdout})
                exports[stem + '.c'], exports[stem] = generated.encode(), data
                raw_stdout = (json.dumps(stdout_rows, indent=2) + '\n').encode()
                exports[stem + '.stdout.json'] = raw_stdout
                manifests[component][variant] = manifest
                probes[component][variant] = {'source_file': stem + '.c', 'source_sha256': sha(generated.encode()),
                                             'binary_file': stem, 'binary_sha256': sha(data), 'ELF': elf,
                                             'stdout_file': stem + '.stdout.json', 'stdout_sha256': sha(raw_stdout),
                                             'compile_flags': list(FLAGS)}
    validate_records(rows)
    binding = None
    if not preflight:
        parent_raw = read_regular(wifi_report, MAX_REPORT)
        artifacts = collect_compiled(trunk, wifi_report)
        binding = compiled_binding_from_bytes(inputs, parent_raw, artifacts, spi.inspect_elf)
        exports.update({n: d for n, d in artifacts.items() if n in compiled_export_names()})
    output.parent.mkdir(parents=True, exist_ok=True)
    for name, data in exports.items():
        target = output.parent / name
        target.write_bytes(data)
        if any(name == 'target-rx-transport-' + component + '-' + variant
               for component, spec in COMPONENTS.items() for variant in spec['variants']):
            target.chmod(0o755)
    report = {'schema_version': 1, 'status': 'PASS', 'profile': 'k2p-4.4',
              'phase': 'early-source-only' if preflight else 'final-module-reference-bound',
              'execution_role': ROLE, 'required_cases': [n for n, _ in CASES], 'checks': rows,
              'source_files': SOURCE_PATHS, 'source_sha256': {k: sha(v.encode()) for k, v in inputs.items()},
              'component_models': COMPONENTS, 'function_manifest': manifests, 'probes': probes,
              'compiled_binding': binding, 'compiler': str(compiler), 'limits': list(LIMITS)}
    output.write_text(json.dumps(report, indent=2) + '\n')
    print('RX transport: ' + str(len(rows)) + ' inert source/MIPS cases PASS')
    return report


