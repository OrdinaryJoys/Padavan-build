def generate_component(inputs, component, variant='current'):
    require(component in COMPONENTS, 'Unknown RX component')
    spec = COMPONENTS[component]
    require(type(variant) is str and variant in spec['variants'], 'Unknown RX compile variant')
    values = literal_data(inputs[spec['harness_key']])
    exact(values.get('SOURCE_PATHS'), spec['paths'], 'RX literal source contract differs: ' + component)
    exact(values.get('FUNCTION_SOURCES'), spec['functions'], 'RX literal function contract differs: ' + component)
    require(model_data_hash(values) == spec['model_data_sha256'], 'RX literal model data differs: ' + component)
    require(set(values['BODY_ORDER']) == set(spec['functions']) and
            len(values['BODY_ORDER']) == len(spec['functions']), 'RX actual function order incomplete')
    local = {key: inputs[flat] for key, flat in spec['source_keys'].items()}
    regions = values.get('FUNCTION_REGIONS', {})
    if component == 'startup':
        exact(regions, spec['function_regions'], 'Startup configured function region differs')
    else:
        require(not regions, 'Unexpected RX source region selection')
    bodies = {}
    for name, key in spec['functions'].items():
        text = local[key]
        if name in regions:
            require(regions[name] == 'prealloc' and text.count(values['PREALLOC_START']) == 1 and
                    text.count(values['PREALLOC_END']) == 1, 'Startup unique configured preallocation region required')
            text = 'static INT desc_ring_free' + text.split(values['PREALLOC_START'], 1)[1].split(values['PREALLOC_END'], 1)[0]
        bodies[name] = function(text, name)
    if component == 'cmdq':
        exact(values['CASES'], [(o['selector'], EXPECTED[n]) for n, o in CASES
                               if o['component'] == component and o['variant'] == variant],
              'CmdQ fixed expected selection differs')
        def segment(text, begin, end):
            require(text.count(begin) == 1 and text.count(end) == 1, 'CmdQ unique source declaration bounds required')
            return begin + text.split(begin, 1)[1].split(end, 1)[0]
        types = segment(local['header'], 'typedef struct _CmdQElmt', '#define NDIS_OID')
        states = segment(local['os'], 'typedef enum _RTMP_TASK_STATUS_', '#define RTMP_OS_TASK_NAME_LEN')
        statuses = []
        for name in ('NDIS_STATUS_SUCCESS', 'NDIS_STATUS_FAILURE', 'NDIS_STATUS_RESOURCES'):
            matches = re.findall(r'^#define\s+' + name + r'\s+0x[0-9a-fA-F]+\s*$', local['linux'], re.M)
            require(len(matches) == 1, 'CmdQ real NDIS declaration differs: ' + name)
            statuses.append(matches[0])
        code = (values['PREFIX'] + '\n' + '\n'.join(statuses) + '\n' + types + '\n' + states +
                '\n' + values['SEAMS'] + '\n' + '\n'.join(bodies[n] for n in values['BODY_ORDER']) + values['MAIN'])
    elif component == 'rx':
        exact(tuple(values['VARIANT_PREFIXES']), spec['variants'], 'RX fixed compile variants differ')
        selectors = [o['selector'] for _, o in CASES if o['component'] == component and o['variant'] == variant]
        exact(values['CASE_NAMES'], selectors, 'RX fixed selector inventory differs')
        exact(values['EXPECTED_ROWS'][variant], {o['selector']: EXPECTED[n] for n, o in CASES
                                               if o['component'] == component and o['variant'] == variant},
              'RX literal typed observations differ')
        anchors = values['SOURCE_ANCHORS']
        require(type(anchors) is dict and anchors and set(anchors) <= set(local), 'RX ABI source anchors absent')
        for key, fragments in anchors.items():
            require(type(fragments) in (list, tuple) and fragments and
                    all(type(f) is str and f and f in local[key] for f in fragments),
                    'RX actual source ABI anchor differs: ' + key)
        # Functional wire constants/types must be actual source declarations,
        # rather than mutually consistent but unrelated synthetic values.
        prefix = values['PREFIX']
        wire = list(anchors['wire_header']) + list(anchors['sizes']) + [anchors['dma_header'][0]]
        wire += list(anchors['rxd_header'])
        wire += list(anchors['frame_header']) + list(anchors['comm_header'])
        require(all(prefix.count(f) == 1 for f in wire), 'RX probe must retain exact actual wire declarations/macros')
        admission = 'if(!(' + '||'.join('!strcmp(name,' + json.dumps(n) + ')' for n in values['CASE_NAMES']) + '))return 91;'
        require(values['SUFFIX'].count('CASE_ADMISSION') == 1, 'RX fixed case admission template differs')
        code = values['VARIANT_PREFIXES'][variant] + prefix + '\n' + \
            '\n'.join(bodies[n] for n in values['BODY_ORDER']) + '\n' + values['SUFFIX'].replace('CASE_ADMISSION', admission)
    elif component == 'pool':
        require(variant == 'build' and spec['variants'] == ('build',), 'Pool requires configured current build variant')
        selectors = [o['selector'] for _, o in CASES if o['component'] == component and o['variant'] == variant]
        exact(values['CASE_NAMES'], selectors, 'Pool fixed selector inventory differs')
        exact(values['EXPECTED_ROWS'], {o['selector']: EXPECTED[n] for n, o in CASES
                                       if o['component'] == component and o['variant'] == variant},
              'Pool fixed typed observations differ')
        anchors = values['SOURCE_ANCHORS']
        require(type(anchors) is dict and anchors and set(anchors) <= set(local), 'Pool source ABI anchors absent')
        for key, fragments in anchors.items():
            require(type(fragments) in (list, tuple) and fragments and
                    all(type(f) is str and f and f in local[key] for f in fragments),
                    'Pool actual source ABI anchor differs: ' + key)
        prefix = values['PREFIX']
        require(prefix.count('#define CONFIG_WIFI_BUILD_SKB') == 1 and
                prefix.count(anchors['ring_header'][0]) == 1, 'Pool actual build/FIFO macro differs')
        # The authoring parent-prefix hash is informational. Current raw wire
        # declarations are independently bound through the locked RX model.
        rx_spec = COMPONENTS['rx']
        rx_values = literal_data(inputs[rx_spec['harness_key']])
        require(model_data_hash(rx_values) == rx_spec['model_data_sha256'], 'Pool shared RX literal model differs')
        rx_anchors = rx_values['SOURCE_ANCHORS']
        wire = list(rx_anchors['wire_header']) + list(rx_anchors['sizes']) + [rx_anchors['dma_header'][0]]
        wire += [f for f in rx_anchors['rxd_header'] if f.startswith('#define RMAC_') and 'INFO_' not in f]
        require(all(prefix.count(f) == 1 for f in wire), 'Pool probe lost actual shared wire declarations')
        for key in ('wire_header', 'sizes', 'dma_header', 'rxd_header'):
            require(all(f in inputs[rx_spec['source_keys'][key]] for f in rx_anchors[key]),
                    'Pool shared actual source declaration differs: ' + key)
        admission = 'if(!(' + '||'.join('!strcmp(name,' + json.dumps(n) + ')' for n in values['CASE_NAMES']) + '))return 91;'
        require(values['SUFFIX'].count('CASE_ADMISSION') == 1, 'Pool fixed case admission template differs')
        code = prefix + '\n' + values['POOL_SEAMS'] + '\n' + \
            '\n'.join(bodies[n] for n in values['BODY_ORDER']) + '\n' + values['SUFFIX'].replace('CASE_ADMISSION', admission)
    else:
        require(variant == 'prealloc' and spec['variants'] == ('prealloc',), 'Startup requires configured preallocation variant')
        exact(values['CASE_NAMES'], [o['selector'] for _, o in CASES if o['component'] == component],
              'Startup fixed selector inventory differs')
        exact(values['EXPECTED_ROWS'], {o['selector']: EXPECTED[n] for n, o in CASES if o['component'] == component},
              'Startup fixed typed observations differ')
        anchors = values['SOURCE_ANCHORS']
        require(type(anchors) is dict and anchors and set(anchors) <= set(local), 'Startup source anchors absent')
        for key, fragments in anchors.items():
            require(type(fragments) in (list, tuple) and fragments and
                    all(type(f) is str and f and f in local[key] for f in fragments),
                    'Startup actual source anchor differs: ' + key)
        require(values['PREFIX'].count('#define RESOURCE_PRE_ALLOC') == 1,
                'Startup source adapter configured preallocation flag absent')
        admission = 'if(!(' + '||'.join('!strcmp(name,' + json.dumps(n) + ')' for n in values['CASE_NAMES']) + '))return 91;'
        require(values['SUFFIX'].count('CASE_ADMISSION') == 1, 'Startup fixed case admission template differs')
        code = values['PREFIX'] + '\n' + '\n'.join(bodies[n] for n in values['BODY_ORDER']) + \
            '\n' + values['SUFFIX'].replace('CASE_ADMISSION', admission)
    require(type(code) is str and 0 < len(code.encode()) <= MAX_SOURCE, 'RX generated C exceeds budget')
    for name, body in bodies.items():
        require(code.count(body) == 1, 'RX actual complete body omitted/duplicated: ' + name)
    manifest = {name: {'source': spec['source_keys'][spec['functions'][name]],
                       'execution': 'whole-function', 'full_body_sha256': sha(body.encode()),
                       'executed_fragment_sha256': sha(body.encode())} for name, body in bodies.items()}
    return code, manifest


def canonical_command(data):
    require(type(data) is bytes and 0 < len(data) <= MAX_COMMAND and b'\0' not in data,
            'Bounded ordinary RX command required')
    return data.decode('utf-8').replace('mt7615_ap/../mt7615/', 'mt7615/')


def command_member(text, path):
    return re.search(r'(?<![A-Za-z0-9_./+-])' + re.escape(path) + r'(?![A-Za-z0-9_./+-])', text) is not None


