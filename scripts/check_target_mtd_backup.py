def require(value,message):
    if not value:raise ValueError(message)

def sha(data):return hashlib.sha256(data).hexdigest()

def exact(left,right,message):
    require(json.dumps(left,sort_keys=True)==json.dumps(right,sort_keys=True),message)

def function(text,name):
    token=r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|/\*[\s\S]*?\*/|//[^\n]*'
    masked=re.sub(token,lambda m:' '*len(m.group()),text)
    pattern=r'(?m)^(?:static\s+)?(?:inline\s+)?(?:void|int|ssize_t|FILE\s*\*|char\s*\*)\s*\b'+re.escape(name)+r'\s*\([^;{}]*\)\s*\{'
    found=list(re.finditer(pattern,masked));require(len(found)==1,'Missing/ambiguous backup function: '+name)
    opening=masked.index('{',found[0].start());depth=0
    for item in re.finditer(token+r'|[{}]',text[opening:]):
        if item.group()=='{':depth+=1
        elif item.group()=='}':
            depth-=1
            if not depth:return text[found[0].start():opening+item.end()]
    raise ValueError('Unterminated backup function')

def load_generator(inputs):
    # Both modules are trusted locked source strings, never imported by path.
    legacy=checked_module(inputs['legacy_harness'],'backup-legacy')
    previous=sys.modules.get('legacy_firmware_harness')
    sys.modules['legacy_firmware_harness']=legacy
    try:module=checked_module(inputs['harness'],'backup')
    finally:
        if previous is None:del sys.modules['legacy_firmware_harness']
        else:sys.modules['legacy_firmware_harness']=previous
    return module

def regenerate(inputs,fixture_root,owner_uid,mode):
    require(type(inputs) is dict and set(inputs)==set(SOURCE_PATHS),'Backup source set')
    require(mode in ('current','baseline','disabled'),'Backup model mode')
    require(type(owner_uid) is int and 0<=owner_uid<2**32,'Backup fixture UID')
    require(type(fixture_root) is str and fixture_root.startswith('/') and len(fixture_root)<4096 and not any(ord(c)<32 for c in fixture_root),'Backup fixture root')
    require('-DMTD_K2P_LEGACY_GUARD=1' in inputs['makefile'],'Backup legacy guard build option')
    module=load_generator(inputs)
    exact(module.SOURCE_PATHS,HARNESS_SOURCE_PATHS,'Backup harness source contract')
    exact(module.CASE_ARGS,CASE_ARGS,'Backup argv contract')
    exact(module.BASELINE_CASES,BASELINE_CASES,'Backup baseline case contract')
    require(module.BASELINE_COMMIT==BASELINE_COMMIT,'Backup baseline revision')
    exact({n:sha(body.encode()) for n,body in module.BASELINE_FUNCTIONS.items()},BASELINE_FUNCTION_HASHES,'Backup literal baseline function hashes')
    bodies=module.BASELINE_FUNCTIONS if mode=='baseline' else {n:function(inputs[key],n) for n,key in FUNCTION_SOURCES.items()}
    texts={key:inputs[key] for key in HARNESS_SOURCE_PATHS}
    code=module.generate_source(texts,fixture_root,owner_uid,baseline=mode=='baseline',disabled_oracle=mode=='disabled')
    require(type(code) is str and 0<len(code.encode())<=MAX_SOURCE,'Backup generated source budget')
    # Disabled oracle deliberately omits the actual main invocation, but keeps
    # the source bodies so body hashing alone cannot make the oracle pass.
    for name,body in bodies.items():require(code.count(body)==1,'Backup actual body omitted/duplicated: '+name)
    require(code.count(inputs['legacy_guard'])==1,'Backup legacy guard body omitted/duplicated')
    return code,bodies

def fixed_records(rows):
    require(type(rows) is list and len(rows)==len(CASES),'Backup record set')
    for row,(name,options) in zip(rows,CASES):
        require(type(row) is dict and set(row)=={'case','inputs','observed'} and row['case']==name,'Backup record schema/order')
        exact(row['inputs'],options,'Backup fixed typed input: '+name)
        observed=row['observed']
        require(type(observed) is dict and set(observed)==set(EXPECTED[name])|{'flags'},'Backup observation schema')
        require(type(observed['flags']) is int and 0<=observed['flags']<2**32,'Backup open flags type')
        exact({k:v for k,v in observed.items() if k!='flags'},EXPECTED[name],'Backup fixed typed outcome: '+name)

def regular(path,limit):
    before=path.lstat()
    require(stat.S_ISREG(before.st_mode) and before.st_nlink==1 and 0<=before.st_size<=limit,'Backup artifact must be bounded single regular file')
    fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
    try:
        opened=os.fstat(fd)
        identity=lambda st:(st.st_dev,st.st_ino,st.st_size,st.st_mtime_ns,st.st_ctime_ns)
        require(stat.S_ISREG(opened.st_mode) and opened.st_nlink==1 and identity(before)==identity(opened),'Backup artifact changed on open')
        chunks=[];remain=limit+1
        while remain:
            data=os.read(fd,min(remain,1024*1024))
            if not data:break
            chunks.append(data);remain-=len(data)
        result=b''.join(chunks)
        require(len(result)==before.st_size and identity(opened)==identity(os.fstat(fd)),'Backup artifact changed/truncated')
        return result
    finally:os.close(fd)

