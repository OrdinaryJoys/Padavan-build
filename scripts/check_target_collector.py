def function(text, name):
    token = r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|/\*[\s\S]*?\*/|//[^\n]*'
    masked = re.sub(token, lambda m: ' ' * len(m.group()), text)
    pattern = r'(?m)^(?:static\s+)?(?:inline\s+)?(?:void|int|ssize_t|pid_t|long\s+long|FILE\s*\*|char\s*\*)\s*\b' + re.escape(name) + r'\s*\([^;{}]*\)\s*\{'
    found = list(re.finditer(pattern, masked))
    require(len(found) == 1, 'Missing/ambiguous collector function: ' + name)
    opening = masked.index('{', found[0].start())
    depth = 0
    for item in re.finditer(token + r'|[{}]', text[opening:]):
        if item.group() == '{':
            depth += 1
        elif item.group() == '}':
            depth -= 1
            if not depth:
                return text[found[0].start():opening + item.end()]
    raise ValueError('Unterminated collector function: ' + name)

